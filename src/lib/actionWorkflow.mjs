// V2.1 GitHub Actions workflow generator. Pure, bounded, and side-effect free.
export const STABLE_ACTION_REF = 'v1.9.0'
export const UPCOMING_ACTION_REF = 'v2.1.0'

const identifier = /^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?$/
const repositoryIdentifier = /^[A-Za-z0-9_.-]{1,100}$/
const tag = /^v(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)(?:-(?:[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$/
const commitSha = /^[a-f0-9]{40}$/i

export function normalizeActionRepository(value) {
  if (value === undefined || value === null || value === 'current') return 'current'
  if (typeof value === 'string' && value.trim() === '') return null
  if (typeof value !== 'string') return null
  const pieces = value.trim().split('/')
  if (pieces.length !== 2) return null
  const [owner, repo] = pieces
  if (!identifier.test(owner) || !repositoryIdentifier.test(repo) || repo === '.' || repo === '..' || repo.endsWith('.git')) return null
  return `${owner}/${repo}`
}

export function normalizeActionRef(value) {
  if (value === undefined || value === null) return STABLE_ACTION_REF
  if (value === '') return null
  if (typeof value !== 'string' || value !== value.trim() || value.length > 80) return null
  return tag.test(value) || commitSha.test(value) ? value : null
}

export function createActionWorkflow(settings = {}) {
  const repository = normalizeActionRepository(settings.repository)
  const reference = normalizeActionRef(settings.ref)
  const trigger = settings.trigger ?? 'manual'
  if (!repository) throw Error('Enter a valid public owner/repository, or select Current repository.')
  if (!reference) throw Error('Use an existing vX.Y.Z tag or a full 40-character commit SHA.')
  if (!['manual', 'main-push'].includes(trigger)) throw Error('Unsupported workflow trigger.')
  for (const key of ['includeRuns', 'failOnReview', 'uploadArtifact']) {
    if (settings[key] !== undefined && typeof settings[key] !== 'boolean') throw Error(`Invalid ${key}: expected true or false.`)
  }
  const needsRuns = settings.includeRuns === true
  const shouldFail = settings.failOnReview === true
  const keepArtifact = settings.uploadArtifact === true
  const body = [
    '# Generated by RepoVerity V2.1. Review this workflow before committing.',
    '# Public metadata audit only. This is not a vulnerability scan.',
    'name: RepoVerity public repository audit',
    'on:',
    '  workflow_dispatch:',
  ]
  if (trigger === 'main-push') body.push('  push:', '    branches: [main]')
  body.push('permissions:', '  contents: read')
  if (needsRuns) body.push('  actions: read')
  body.push(
    'jobs:',
    '  audit:',
    '    runs-on: ubuntu-24.04',
    '    timeout-minutes: 8',
    '    steps:',
    '      - name: RepoVerity evidence audit',
    `        uses: kobrymoataz/repoverity@${reference}`,
    '        with:',
    repository === 'current' ? '          repository: ${{ github.repository }}' : `          repository: ${repository}`,
    '          github_token: ${{ github.token }}',
    `          include_runs: '${needsRuns}'`,
    `          fail_on_review: '${shouldFail}'`,
    '          output_path: repoverity-report.json',
  )
  if (keepArtifact) body.push(
    '      - name: Preserve JSON audit report',
    '        if: always()',
    '        uses: actions/upload-artifact@v4',
    '        with:',
    '          name: repoverity-report',
    '          path: repoverity-report.json',
    '          if-no-files-found: warn',
    '          retention-days: 7',
  )
  return body.join('\n') + '\n'
}
